export function getZoneForStage(stage: number): {
  id: 'little_italy' | 'docks' | 'financial' | 'casino' | 'lockdown';
  name: string;
  worldLabel: string;
  isChaos: boolean;
  chaosTier: number;
} {
  if (stage > 50) {
    const lockdownTier = Math.floor((stage - 51) / 20) + 1;
    return {
      id: 'lockdown',
      name: `Federal Lockdown (Heat ${lockdownTier})`,
      worldLabel: `HEAT-${lockdownTier}`,
      isChaos: true,
      chaosTier: lockdownTier,
    };
  }
  if (stage > 30) {
    return {
      id: 'casino',
      name: 'The Casino Strip',
      worldLabel: 'Casino Strip',
      isChaos: false,
      chaosTier: 0,
    };
  }
  if (stage > 20) {
    return {
      id: 'financial',
      name: 'Financial District',
      worldLabel: 'Downtown',
      isChaos: false,
      chaosTier: 0,
    };
  }
  if (stage > 10) {
    return {
      id: 'docks',
      name: 'Waterfront Docks',
      worldLabel: 'The Docks',
      isChaos: false,
      chaosTier: 0,
    };
  }
  return {
    id: 'little_italy',
    name: 'Little Italy Back Alleys',
    worldLabel: 'Little Italy',
    isChaos: false,
    chaosTier: 0,
  };
}

